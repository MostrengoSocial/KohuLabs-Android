// The data model's one check, and the Worker's copy of it. No dependencies (Node 22+):
//   node db/check-schema.mjs           checks, as CI does
//   node db/check-schema.mjs --write   after changing db/migrations/: rewrites api/migrations.js
//
// 1. The phone's database (Room, android/app/schemas/) and the cloud one (db/migrations/, D1) have the same tables
//    and columns, with the same types and NOT NULL. Only the cloud has user_id and seq (and sync_counter); only the
//    phone has its outbox (changes not uploaded yet). google_accounts (Google sign-in for the import) is cloud only too.
// 2. api/migrations.js, which the Worker runs to set up D1 and uses to know each table's columns, matches
//    db/migrations/. Workers cannot read .sql files, so it is generated from them.
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const CLOUD_ONLY_COLUMNS = ['user_id', 'seq'];
const CLOUD_ONLY_TABLES = ['sync_counter', 'google_accounts'];
const PHONE_ONLY_TABLES = ['outbox'];

const here = new URL('.', import.meta.url);
const roomDir = new URL('../android/app/schemas/com.kohulabs.android.data.FoundersDatabase/', here);
const latest = readdirSync(roomDir).filter((f) => f.endsWith('.json')).sort((a, b) => parseInt(b) - parseInt(a))[0];
const room = JSON.parse(readFileSync(new URL(latest, roomDir))).database;

// Each migration as separate statements (comments removed; D1 runs them one by one).
const migrations = readdirSync(new URL('migrations/', here)).filter((f) => f.endsWith('.sql')).sort().map((name) => ({
  name,
  statements: readFileSync(new URL(`migrations/${name}`, here), 'utf8').replace(/--[^\n]*/g, '').split(';').map((s) => s.replace(/\s+/g, ' ').trim()).filter(Boolean)
}));
const d1 = new DatabaseSync(':memory:');
for (const m of migrations) for (const s of m.statements) d1.exec(s);

const problems = [];
const cloudTables = d1.prepare("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY rowid").all().map((t) => t.name);
const roomTables = room.entities.map((e) => e.tableName);
for (const t of cloudTables) if (!roomTables.includes(t) && !CLOUD_ONLY_TABLES.includes(t)) problems.push(`table ${t} is in db/migrations but not on the phone`);
const tables = {};
for (const e of room.entities) {
  if (PHONE_ONLY_TABLES.includes(e.tableName)) continue;
  if (!cloudTables.includes(e.tableName)) { problems.push(`table ${e.tableName} is on the phone but not in db/migrations`); continue; }
  const cloud = new Map(d1.prepare(`PRAGMA table_info(${e.tableName})`).all().map((c) => [c.name, c]));
  for (const c of CLOUD_ONLY_COLUMNS) { if (!cloud.has(c)) problems.push(`${e.tableName}: no ${c} in the cloud table`); cloud.delete(c); }
  tables[e.tableName] = e.fields.map((f) => f.columnName);
  for (const f of e.fields) {
    const c = cloud.get(f.columnName);
    if (!c) { problems.push(`${e.tableName}.${f.columnName} is on the phone but not in the cloud`); continue; }
    if (c.type !== f.affinity) problems.push(`${e.tableName}.${f.columnName}: ${f.affinity} on the phone, ${c.type} in the cloud`);
    if (!!c.notnull !== !!f.notNull && f.columnName !== 'id') problems.push(`${e.tableName}.${f.columnName}: NOT NULL differs`);
    cloud.delete(f.columnName);
  }
  for (const name of cloud.keys()) problems.push(`${e.tableName}.${name} is in the cloud but not on the phone`);
}

const generated = `// GENERATED by \`node db/check-schema.mjs --write\` from db/migrations/. Do not edit.
// The Worker applies these to D1 in order (api/sync.js) and syncs these tables and columns.
export const MIGRATIONS = ${JSON.stringify(migrations, null, 2)};

export const TABLES = ${JSON.stringify(tables, null, 2)};
`;
const target = new URL('../api/migrations.js', here);
if (process.argv.includes('--write')) writeFileSync(target, generated);
else {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch (_) { /* missing */ }
  if (current !== generated) problems.push('api/migrations.js is out of date: run node db/check-schema.mjs --write');
}

if (problems.length) { console.error('Schema problems:\n  ' + problems.join('\n  ')); process.exit(1); }
console.log(`Schemas match: ${Object.keys(tables).length} synced tables (Room version ${room.version}, ${migrations.length} cloud migrations).`);
